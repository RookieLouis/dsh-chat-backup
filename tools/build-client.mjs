import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = fs.readFileSync(path.join(root, 'src', 'client.js'), 'utf8').replace(/^\uFEFF/, '');
if (/^\s*import\s/m.test(source)) throw new Error('Client source must use native renderer dependencies supplied by the factory.');
const embedded = source.replace(/^export (?=(?:const|function)\b)/gm, '');
if (/^\s*export\s/m.test(embedded)) throw new Error('Unsupported client export.');
const output = `// Generated by tools/build-client.mjs. Edit src/client.js and rebuild.
window.__ModuleLoader__.load({
  id: 'dsh-chat-backup',
  factory(require) {
    const React = require('react');
    const primitives = require('@deepseek-ai/dsh-client-ui-primitives');
${embedded}
    return createBackupClient(React, primitives);
  },
});
`;
fs.writeFileSync(path.join(root, 'lib', 'client.js'), output, 'utf8');
console.log('Built dsh-chat-backup native client (' + Buffer.byteLength(output) + ' bytes)');
